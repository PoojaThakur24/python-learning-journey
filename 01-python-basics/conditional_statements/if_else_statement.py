""" if..else statement: The if..else statement executes one block if the condition is true, 
                        otherwise it executes another block. """


""" Greater of Two Numbers: Take two numbers and display the greater number. """

num1 = int(input('Enter first number: '))
num2 = int(input('Enter second number: '))

if num1 > num2:
    print(f'{num1} is Greater')
else:
    print(f'{num2} is Greater.')