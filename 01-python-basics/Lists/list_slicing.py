""" List Slicing
Create a list of ten numbers and print:

First 5 elements

Last 3 elements

Elements from index 2 to 6 """

list = [2, 1, 8, 4, 0, 2, 5, 4, 10, 3]

print(f'First five elements of list : {list[0:5]}')

print(f'Last three elements of list: {list[-3:]}')

print(f'Elements from index 2 to 6: {list[2:7]}')