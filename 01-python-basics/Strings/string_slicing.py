""" String Slicing
Create a string "Programming" and print: Print First 4 characters Last 4 characters
Characters from index 2 to 6 """

str = 'Programming'

print(f'First four charaters of String: {str[0:4]} ')
print(f'Last four charaters of String: {str[-4:]} ')
print(f'Characters from index 2 to 6: {str[2:7]}')

