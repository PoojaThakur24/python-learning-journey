""" 
Boolean Comparison

Take two numbers and print the results of a > b, a < b, and a == b. """

num1 =  int(input('Enter first number: '))
num2 = int(input('Enter second number: '))

print(f'Is first number greater? {num1 > num2}')
print(f'Is first number smaller? {num1 < num2}')
print(f'Are both numbers equal? {num1 == num2}')