""" Integer Calculator

Take two integers as input and display their sum, difference, product, and division. """

num1 = int(input('Enter first number: '))
num2 = int(input('Enter second number: '))

sum = num1 + num2
difference = num1 - num2
product = num1 * num2
division = num1 / num2 

print(f'Sum of two number is: {sum}')
print(f'Difference between two numbers is: {difference}')
print(f'Product of two numbers is: {product}')
print(f'Division of two number is: {division}')