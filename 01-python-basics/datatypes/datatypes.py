"""
Identify Data Types

Create variables containing an integer, float, string, and Boolean value. 
Print each variable and its data type using type(). """

age = 24
height = 5.6
name = 'Pooja'
is_learing_python = True

print(f'Age: {age}')
print(f'Height: {height}')
print(f'Name: {name}')
print(f'Learning Python: {is_learing_python}')

print(f'Data type of age: {type(age)}')
print(f'Data type of height: {type(height)}')
print(f'Data type of name: {type(name)}')
print(f'Data type of learning python : {type(is_learing_python)}')