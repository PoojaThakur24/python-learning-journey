""" 
Tuple Operations

Create a tuple of five elements. 
Print its length, first element, last element, and count of a given value. """

numbers = (10,20,30,40,50)

print(f'Length of the tuple: {len(numbers)}')
print(f'First element of the tuple: {numbers[0]}')
print(f'Last element of the tuple: {numbers[-1]}')
print(f'Count of 20: {numbers.count(20)}')
