""" Create variables storing an integer, float, string, and Boolean. 
Print their values and data types using `type()`. """

age = 24
height = 5.6
name = 'Pooja'
is_learning_python = True

print('Age: ', age)
print('Height: ', height)
print('Name: ', name)
print('Learning Python: ', is_learning_python)

print('Data type of Age: ',type(age))
print('Data type of Height: ', type(height))
print('Data type of Name: ', type(name))
print('Data type of Learning Python : ', type(is_learning_python))

